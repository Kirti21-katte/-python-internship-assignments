# Python Program to Demonstrate Different Data Types

# Declaring variables
integer_num = 80
float_num = 31.21
string_text = "Python, DataTypes!"
boolean_value = True

# Printing values and their data types
print("Integer Value:", integer_num)
print("Data Type:", type(integer_num))

print("\nFloat Value:", float_num)
print("Data Type:", type(float_num))

print("\nString Value:", string_text)
print("Data Type:", type(string_text))

print("\nBoolean Value:", boolean_value)
print("Data Type:", type(boolean_value))

